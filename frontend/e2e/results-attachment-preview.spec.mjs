import { expect, test } from './support/isolatedTest.mjs';
import { createAssessmentAttempt, completeAttempt } from './support/assessmentAttemptFixture.mjs';
import { login } from './support/gesture-helpers.mjs';
import { expectDialogContained } from './support/dialogGeometry.mjs';
import { readFileSync } from 'node:fs';

test('uploaded student image and accompanying text are visible together in the answer dialog', async ({ page, context }, info) => {
  const { course, loginId, questions } = await createAssessmentAttempt(page, context, 'tasks', String(info.project.use.viewport.width));
  await completeAttempt(page, questions);
  const buffer = readFileSync(new URL('../public/الأيقونة.png', import.meta.url));
  const question = page.locator('.assessment-question').filter({ hasText: 'إجابة الاستعادة بالمرفق' });
  await question.locator('input[type=file]').setInputFiles({ name: 'answer.png', mimeType: 'image/png', buffer });
  await question.locator('textarea').fill('هذه إجابتي مع الصورة المرفقة');
  await page.getByRole('button', { name: 'إرسال', exact: true }).click();
  await expect(page.getByText('تم الإرسال', { exact: true })).toBeVisible();
  await page.goto('about:blank');
  await context.clearCookies();
  await login(page);
  await page.goto('dashboard?panel=results');
  await page.getByRole('combobox', { name: 'القسم', exact: true }).locator('..').click();
  const taskOption = page.getByRole('option', { name: course.title, exact: true });
  if (info.project.use.hasTouch) await taskOption.tap();
  else await taskOption.click();
  await expect(page.getByRole('combobox', { name: 'القسم', exact: true })).toHaveValue(course.title);
  const eye = page.locator('.results-entry').filter({ hasText: loginId }).getByRole('button', { name: /عرض إجابة/ });
  await eye.click();
  const dialog = page.getByRole('dialog', { name: 'الإجابة', exact: true });
  await expect(dialog).toContainText('هذه إجابتي مع الصورة المرفقة');
  const image = dialog.getByRole('img', { name: 'answer.png', exact: true });
  await expect(image).toBeVisible();
  await expect.poll(() => image.evaluate(element => element.naturalWidth)).toBeGreaterThan(0);
  await image.scrollIntoViewIfNeeded();
  await page.screenshot({ path: info.outputPath('uploaded-answer-mobile.png') });
  const fileUrl = await dialog.getByRole('link', { name: 'فتح الملف الأصلي', exact: true }).getAttribute('href');
  const storedFile = await page.request.get(fileUrl);
  expect(storedFile.status()).toBe(200);
  expect((await storedFile.body()).equals(buffer)).toBe(true);
  const unsigned = new URL(fileUrl);
  unsigned.search = '';
  expect([403, 404]).toContain((await page.request.get(unsigned.href)).status());
  await expectDialogContained(dialog);
  await dialog.getByRole('button', { name: 'إغلاق', exact: true }).click();
  await expect(dialog).toBeHidden();
  await page.route('**/storage/assessment-attachments/**', route => route.abort('failed'));
  await eye.click();
  await expect(dialog.getByRole('alert')).toContainText('تعذّر عرض المرفق');
  await expect(dialog.getByRole('link', { name: 'فتح الملف الأصلي', exact: true })).toHaveAttribute('href', /storage\/assessment-attachments/);
  await expectDialogContained(dialog);
});
